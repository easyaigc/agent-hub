/** Debug acceptance-only first-Activity selection. The opaque product Intent carries no lease/configuration. */
internal object NativeChatNotificationColdStart {
    const val HOOK_VERSION = 1
    private const val ROUTER_NAMESPACE = NativeChatNotificationColdRouterFiles.NAMESPACE
    private const val ROUTER_RECORD = NativeChatNotificationColdRouterFiles.RECORD
    val processNonce = UUID.randomUUID().toString()
    val activityEntries = AtomicInteger()
    val defaultSelections = AtomicInteger()
    @Volatile private var permit: NativeChatNotificationColdPlan? = null
    @Volatile var active: Binding? = null; private set
    class Binding(val plan: NativeChatNotificationColdPlan, val storage: NativeSessionStorage, val scope: NativeChatNotificationAcceptanceScope) {
        val ports = NativeChatNotificationColdPorts(plan, false)
        lateinit var session: MobileSession
        val newIntentHandled = AtomicInteger()
        var coordinator: NativeChatNotificationCoordinator? = null
        fun matches(value: MobileSession) = ::session.isInitialized && session === value
        fun sessionOrNull(): MobileSession? = if(::session.isInitialized) session else null
    }
    private fun eligible(context: Context) = BuildConfig.DEBUG && context.packageName == "com.easyai.agenthub.android.acceptance"
    private fun guard(context: Context) = require(eligible(context)) { "Exact independent debug acceptance package required" }
    fun requireHooks(context: Context) {
        guard(context)
        for ((type, name) in listOf(MainActivity::class.java to "P9_NOTIFICATION_COLD_HOOK", MobileSession::class.java to "P9_NOTIFICATION_COLD_PORT_HOOK")) {
            val field = type.getField(name)
            require(field.type == Int::class.javaPrimitiveType && field.getInt(null) == HOOK_VERSION) { "Parent cold-start overlay is not installed" }
        }
    }
    private fun existingKey() {
        val keys = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        require(keys.getKey("agent-hub-mobile-v1", null) is javax.crypto.SecretKey) { "Existing acceptance installation encryption key required; no key is imported/generated by this fixture" }
    }
    private fun router(context: Context): NativeSessionStorage { guard(context); return NativeSessionStorage(context, ROUTER_NAMESPACE) }
    private fun readMarker(context: Context): JSONObject? {
        guard(context)
        if(!NativeChatNotificationColdRouterFiles.hasReadableMarker(context.noBackupFilesDir))return null
        existingKey()
        val store = router(context)
        val raw = checkNotNull(store.read(ROUTER_RECORD)) { "Unknown/unfinished cold router material preserved; default storage stays unopened" }
        require(raw.toByteArray().size <= 16_384)
        return JSONObject(raw).also {
            NativeChatNotificationWire.keys(it, setOf("version", "original", "phase", "reader"))
            require(it.get("version") == 1 && it.getString("phase") in setOf("armed", "selected", "complete"))
            NativeChatNotificationColdPlan.decode(it.getJSONObject("original"))
            if(it.getString("phase") == "armed") require(it.isNull("reader")) else {
                val reader = it.getJSONObject("reader"); NativeChatNotificationWire.keys(reader, setOf("pid", "nonce", "selectedAt", "completedAt", "savedStatePresent"))
                require(NativeChatNotificationWire.long(reader, "pid") in 1..Int.MAX_VALUE.toLong())
                NativeChatNotificationColdPlan.uuid(reader.getString("nonce")); NativeChatNotificationWire.long(reader, "selectedAt"); require(reader.get("savedStatePresent") is Boolean)
                if(it.getString("phase") == "complete") NativeChatNotificationWire.long(reader, "completedAt") else require(reader.isNull("completedAt"))
            }
        }
    }
    private fun apkHash(context: Context, runner: Boolean): String {
        guard(context)
        val info = if(!runner) context.applicationInfo else context.packageManager.getApplicationInfo(context.packageName + ".test", 0).also {
            require(context.packageManager.checkSignatures(context.packageName, it.packageName) == android.content.pm.PackageManager.SIGNATURE_MATCH)
        }
        require(info.splitSourceDirs.isNullOrEmpty()) { "Single frozen app/runner APK required" }
        val file = File(info.sourceDir); require(file.length() in 1..128L * 1024 * 1024)
        return file.inputStream().use { input -> val hash = MessageDigest.getInstance("SHA-256"); val buffer = ByteArray(64 * 1024)
            var total = 0L
            while(true) { val count = input.read(buffer); if(count < 0)break; total += count; require(total <= 128L * 1024 * 1024); hash.update(buffer, 0, count) }
            hash.digest().joinToString("") { "%02x".format(it) }
        }
    }
    fun originalReceipt(storage: NativeSessionStorage, plan: NativeChatNotificationColdPlan): NativeChatNoticeReceipt {
        val values = JSONObject(checkNotNull(storage.read(NativeChatNotificationStore.RECORD))).getJSONArray("receipts")
        require(values.length() == 1)
        return NativeChatNotificationCodec.receipt(values.getJSONObject(0)).also { require(it.ticket == plan.ticket) }
    }
    private fun verifySeed(context: Context, plan: NativeChatNotificationColdPlan): NativeSessionStorage {
        val scope = NativeChatNotificationAcceptanceScope.create(context, plan.lease); val storage = scope.storage(context)
        require(storage.storedBytes("metadata") in 1..262_144 && storage.storedBytes(NativeChatNotificationStore.RECORD) in 1..131_072)
        val receipt = originalReceipt(storage, plan)
        require(!receipt.consumed && NativeChatRecoveryCanonical.hash(NativeChatNotificationCodec.receipt(receipt)) == plan.receiptHash)
        val expectedTarget = if(plan.case == NativeChatNotificationColdCase.WRONG_RUNTIME) plan.target.copy(runtimeId = "foreign-cold-runtime") else plan.target
        require(receipt.event.target == expectedTarget && receipt.event.threadId == plan.originalThread && receipt.lease.credentialEpoch == plan.authority)
        val metadata = checkNotNull(storage.metadata()); val clients = metadata.getJSONArray("clients"); require(clients.length() == 1)
        val client = decodeClient(clients.getJSONObject(0))
        require(client.id == plan.target.hostId && NativeChatNoticeTarget.from(checkNotNull(client.scope)) == plan.target && client.endpoint == plan.endpoint)
        require(storage.token(client.id) == plan.storedToken)
        require(storage.read(NativeChatNotificationIdentity.RECORD) == null && storage.read(NativeChatNotificationForegroundStore.RECORD) == null && storage.read(NativeChatNotificationRecoveryStore.RECORD) == null)
        return storage
    }
    /** IO preflight only: no Activity or Session is constructed and no default store is opened. */
    fun prepareReader(context: Context, lease: String): NativeChatNotificationColdPlan {
        guard(context); requireHooks(context); existingKey(); NativeChatNotificationColdPlan.uuid(lease)
        require(activityEntries.get() == 0 && defaultSelections.get() == 0 && active == null && permit == null)
        val marker = checkNotNull(readMarker(context)); require(marker.getString("phase") == "armed") { "Inspect the original attempt; never replay an unknown/completed cold startup" }
        val plan = NativeChatNotificationColdPlan.decode(marker.getJSONObject("original"))
        require(plan.lease == lease && plan.writerPid != Process.myPid() && plan.writerNonce != processNonce)
        val processes = checkNotNull(context.getSystemService(ActivityManager::class.java).runningAppProcesses)
        require(processes.filter { it.uid == Process.myUid() }.none { it.pid == plan.writerPid }) { "Original writer process must have exited" }
        val now = System.currentTimeMillis(); require(plan.issuedAt <= now + 60_000 && now - plan.issuedAt <= NativeChatNotificationColdPlan.TTL)
        require(apkHash(context, false) == plan.appHash && apkHash(context, true) == plan.runnerHash)
        verifySeed(context, plan); permit = plan; return plan
    }
    fun strictTicket(context: Context, intent: Intent): String {
        guard(context)
        require(intent.action == NativeChatNotificationPlatform.ACTION && intent.clipData == null && intent.selector == null && intent.categories.isNullOrEmpty())
        require(intent.extras?.keySet() == setOf(NativeChatNotificationPlatform.TICKET))
        val value = NativeChatNotificationColdPlan.uuid(checkNotNull(intent.getStringExtra(NativeChatNotificationPlatform.TICKET)))
        require(intent.component?.packageName == context.packageName && intent.component?.className == MainActivity::class.java.name)
        require(intent.data?.toString() == "agenthub-chat-notice://${context.packageName}/$value")
        return value
    }
    /** Parent calls before constructing the default storage/Session. An armed invalid launch fails closed. */
    fun selectForActivity(context: Context, intent: Intent, retained: MobileSession?, restoredActivity: Boolean): Binding? {
        if(!eligible(context))return null
        activityEntries.incrementAndGet()
        active?.let { current -> require(retained === current.session); return current }
        val marker = readMarker(context) ?: return null
        require(marker.getString("phase") == "armed")
        val plan = checkNotNull(permit) { "A fresh reader process must complete the fixed lease preflight before its first Activity" }
        require(plan.fingerprint == NativeChatNotificationColdPlan.decode(marker.getJSONObject("original")).fingerprint)
        require(activityEntries.get() == 1 && defaultSelections.get() == 0 && retained == null)
        require(strictTicket(context, intent) == plan.ticket)
        require(System.currentTimeMillis() - plan.issuedAt <= NativeChatNotificationColdPlan.TTL)
        val storage = verifySeed(context, plan)
        marker.put("phase", "selected").put("reader", JSONObject().put("pid", Process.myPid()).put("nonce", processNonce)
            .put("selectedAt", System.currentTimeMillis()).put("completedAt", JSONObject.NULL).put("savedStatePresent", restoredActivity))
        router(context).write(ROUTER_RECORD, marker.toString())
        val binding = Binding(plan, storage, NativeChatNotificationAcceptanceScope.create(context, plan.lease))
        active = binding
        binding.session = MobileSession(storage, binding.ports.sessionReads, binding.ports.commands)
        return binding
    }
    /** Diagnostic acknowledgement after the real Activity dispatcher handled a duplicate original. */
    fun afterNewIntent(context: Context, intent: Intent, session: MobileSession) {
        val binding = active ?: return
        if(!eligible(context) || !binding.matches(session) || intent.action != NativeChatNotificationPlatform.ACTION)return
        if(runCatching { strictTicket(context, intent) }.getOrNull() == binding.plan.ticket)binding.newIntentHandled.incrementAndGet()
    }
    fun noteDefaultStorage(context: Context) { if(eligible(context))defaultSelections.incrementAndGet() }
    fun bound(session: MobileSession) = active?.matches(session) == true
    /** Preserve P8 configuration/lifecycle while a cold fixture never enumerates real MediaStore data. */
    fun recentPhotoSource(context: Context, session: MobileSession): NativeRecentPhotoSource? {
        if(!bound(session))return null
        guard(context)
        return object : NativeRecentPhotoSource {
            override fun access() = NativePhotoAccess.NONE
            override fun permissions() = if(android.os.Build.VERSION.SDK_INT >= 33) arrayOf(android.Manifest.permission.READ_MEDIA_IMAGES) else arrayOf(android.Manifest.permission.READ_EXTERNAL_STORAGE)
            override fun observe(changed: () -> Unit): () -> Unit = {}
            override suspend fun snapshot(limit: Int): List<NativeRecentPhoto> = emptyList()
            override suspend fun thumbnail(photo: NativeRecentPhoto): android.graphics.Bitmap? = null
            override suspend fun input(photo: NativeRecentPhoto): LocalAttachmentInput = error("Cold route acceptance never reads photo originals")
        }
    }
    fun pollingAllowed(storage: NativeSessionStorage) = active?.storage?.coordinationKey != storage.coordinationKey
    fun coordinator(context: Context, scope: CoroutineScope, port: NativeChatNotificationSessionPort, language: String): NativeChatNotificationCoordinator? {
        val binding = active ?: return null
        guard(context); require(port.storage.coordinationKey == binding.storage.coordinationKey)
        return NativeChatNotificationCoordinator(scope, port, NativeChatNotificationPlatform.forAcceptance(context, NativeL10n(context, language), binding.scope, binding.storage),
            binding.ports.notices, NativeChatNotificationThreadLocator(binding.ports::locatorReads), applicationId = context.packageName).also { binding.coordinator = it }
    }
    suspend fun seedWriter(context: Context, lease: String, case: NativeChatNotificationColdCase): NativeChatNotificationColdPlan {
        guard(context); requireHooks(context); existingKey(); NativeChatNotificationColdPlan.uuid(lease)
        require(activityEntries.get() == 0 && defaultSelections.get() == 0 && active == null)
        require(readMarker(context) == null) { "An original cold lease is already armed; inspect/disarm it instead of replaying" }
        val scope = NativeChatNotificationAcceptanceScope.create(context, lease)
        val root = File(context.noBackupFilesDir, "P9-native-system-$lease"); require(!root.exists()) { "Cold lease namespace must be fresh" }
        val storage = scope.storage(context)
        val template = NativeChatNotificationColdPlan(lease, case, UUID.randomUUID().toString(), Process.myPid(), processNonce, System.currentTimeMillis(),
            apkHash(context, false), apkHash(context, true), "0".repeat(64), "0".repeat(64))
        val ports = NativeChatNotificationColdPorts(template, true)
        val client = withContext(Dispatchers.Main.immediate) {
            val session = MobileSession(storage, ports.sessionReads, ports.commands); session.resetAcceptance(ports.sessionReads, ports.commands)
            val client = session.connect("Owned cold fixture", template.endpoint, template.token)
            session.selectThread(ports.sessionReads.workspace(client).threads.single { it.id == template.originalThread }); session.text = template.originalDraft
            session.selectThread(ports.sessionReads.workspace(client).threads.single { it.id == template.otherThread }); session.text = template.otherDraft
            session.leaveForeground(); require(session.operationRecords.isEmpty()); client
        }
        storage.awaitQueuedWrites()
        val notices = NativeChatNotificationStore(storage); notices.update(NativeChatNotificationColdPlan::seedPreferences)
        val captured = NativeChatNotificationSavedConnection.capture(client, template.token)
        val target = if(case == NativeChatNotificationColdCase.WRONG_RUNTIME) template.target.copy(runtimeId = "foreign-cold-runtime") else template.target
        val then = template.issuedAt - if(case == NativeChatNotificationColdCase.EXPIRED) NativeChatNotificationStore.TTL_MILLIS + 1_000 else 0
        val event = NativeChatNotificationEvent(NativeChatNotificationWire.hash("cold-event:$lease"), target, NativeChatNoticeKind.COMPLETED,
            java.time.Instant.ofEpochMilli(then).toString(), template.originalThread, threadTitle = "Owned cold original", taskSummary = "Fixed acceptance route")
        val noticeLease = notices.bind(target, captured.snapshot.credentialEpoch)
        check(notices.preferences().permits(event) && notices.current(noticeLease)) { "Cold fixture must explicitly permit its completion event before claim; preserve this failed lease" }
        val receipt = checkNotNull(notices.claim(event, noticeLease, then)) { "Cold fixture claim rejected before router arm; preserve this failed lease without replay" }
        // A claimed route fixture is not represented as an OS-posted notification.
        val plan = template.copy(ticket = receipt.ticket, receiptHash = NativeChatRecoveryCanonical.hash(NativeChatNotificationCodec.receipt(receipt)), authority = captured.snapshot.credentialEpoch)
        if(case == NativeChatNotificationColdCase.WRONG_CREDENTIAL)storage.setToken(client.id, plan.storedToken)
        verifySeed(context, plan); require(ports.forbiddenCommands.get() == 0)
        router(context).write(ROUTER_RECORD, JSONObject().put("version", 1).put("original", plan.json()).put("phase", "armed").put("reader", JSONObject.NULL).toString())
        proof(context, plan, "writer-armed", JSONObject().put("defaultSelections", defaultSelections.get()).put("activityEntries", activityEntries.get()))
        return plan
    }
    fun completeReader(context: Context, binding: Binding) {
        guard(context); require(active === binding && binding.ports.forbiddenCommands.get() == 0 && binding.ports.notificationCommands.get() == 0)
        require(activityEntries.get() == 1 && defaultSelections.get() == 0 && binding.newIntentHandled.get() == 1)
        val receipt = originalReceipt(binding.storage, binding.plan)
        require(receipt.consumed == (binding.plan.case == NativeChatNotificationColdCase.ORIGINAL))
        require(NativeChatRecoveryCanonical.hash(NativeChatNotificationCodec.receipt(receipt.copy(consumed = false))) == binding.plan.receiptHash)
        val marker = checkNotNull(readMarker(context)); require(marker.getString("phase") == "selected")
        require(marker.getJSONObject("reader").getInt("pid") == Process.myPid() && marker.getJSONObject("reader").getString("nonce") == processNonce)
        require(NativeChatNotificationColdPlan.decode(marker.getJSONObject("original")).fingerprint == binding.plan.fingerprint)
        marker.put("phase", "complete"); marker.getJSONObject("reader").put("completedAt", System.currentTimeMillis())
        router(context).write(ROUTER_RECORD, marker.toString())
        proof(context, binding.plan, "reader-complete", JSONObject().put("defaultSelections", defaultSelections.get()).put("activityEntries", activityEntries.get())
            .put("newIntentHandled", binding.newIntentHandled.get()).put("locatorCursors", JSONArray(binding.ports.locatorCursors)).put("forbiddenCommands", binding.ports.forbiddenCommands.get()).put("notificationCommands", binding.ports.notificationCommands.get())
            .put("receiptConsumed", receipt.consumed).put("receiptState", receipt.state).put("receiptHashMatched", true)
            .put("receiptTarget", NativeChatNotificationCodec.target(receipt.event.target)).put("authorityMatched", receipt.lease.credentialEpoch == binding.plan.authority))
    }
    /** Failure observation preserves the selected original; it never completes, cancels or replays it. */
    suspend fun recordReaderFailure(context: Context) {
        guard(context); val binding = active ?: return
        val details = withContext(Dispatchers.Main.immediate) {
            JSONObject().put("defaultSelections", defaultSelections.get()).put("activityEntries", activityEntries.get())
                .put("openState", binding.coordinator?.openState ?: "not-configured").put("newIntentHandled", binding.newIntentHandled.get())
                .put("locatorCursors", JSONArray(binding.ports.locatorCursors)).put("forbiddenCommands", binding.ports.forbiddenCommands.get())
                .put("notificationCommands", binding.ports.notificationCommands.get()).put("selectedThread", binding.sessionOrNull()?.selectedThread)
                .put("draftHash", binding.sessionOrNull()?.text?.let(NativeChatNotificationWire::hash))
        }
        withContext(Dispatchers.IO) { proof(context, binding.plan, "reader-failed-unresolved", details) }
    }
    /** Fresh observer only: releases the single router slot after the original reader result is complete. Retains evidence storage. */
    fun disarmCompleted(context: Context, lease: String) {
        guard(context); requireHooks(context); existingKey(); NativeChatNotificationColdPlan.uuid(lease)
        require(activityEntries.get() == 0 && active == null)
        val marker = checkNotNull(readMarker(context)); val plan = NativeChatNotificationColdPlan.decode(marker.getJSONObject("original"))
        require(plan.lease == lease && marker.getString("phase") == "complete")
        require(marker.getJSONObject("reader").getInt("pid") != Process.myPid() && marker.getJSONObject("reader").getString("nonce") != processNonce)
        val processes = checkNotNull(context.getSystemService(ActivityManager::class.java).runningAppProcesses)
        require(processes.filter { it.uid == Process.myUid() }.none { it.pid == marker.getJSONObject("reader").getInt("pid") })
        proof(context, plan, "observer-disarmed", JSONObject().put("privateLeaseData", "retained for parent evidence review; no default store/keys removed"))
        router(context).remove(ROUTER_RECORD)
    }
    private fun proof(context: Context, plan: NativeChatNotificationColdPlan, role: String, details: JSONObject) {
        val folder = File(context.filesDir, "acceptance/P9-notification-cold/${plan.lease}").apply { mkdirs() }
        File(folder, "$role-${UUID.randomUUID()}.json").writeText(JSONObject().put("version", 1).put("role", role).put("planHash", plan.fingerprint)
            .put("lease", plan.lease).put("case", plan.case.wire).put("pid", Process.myPid()).put("processNonce", processNonce)
            .put("writerPid", plan.writerPid).put("writerNonce", plan.writerNonce).put("appHash", plan.appHash).put("runnerHash", plan.runnerHash)
            .put("details", details).put("osBoundaryEvidence", "not-tested; claimed receipt fixture is not represented as posted").toString())
    }
}
